"use strict";

// Funktion för att räkna ut area
function calculateArea(width, height) {
  let area = width * height; // Räknesätt area
  return area; // Return för att kunna använda det utanför funtionen
}

// Resultat uträkningar av olika area
console.log("Arean är " + calculateArea(4, 6));
console.log("Arean är " + calculateArea(7, 9));
console.log("Arean är " + calculateArea(5, 10));
